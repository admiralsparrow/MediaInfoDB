_alias_to_canonical: dict[str, str] = {}
_all_tokens: list[str] = []

for canonical, aliases in PROVIDERS.items():
    _alias_to_canonical[canonical] = canonical
    _all_tokens.append(canonical)
    for alias in aliases:
        _alias_to_canonical[alias] = canonical
        _all_tokens.append(alias)

# Sort longest first so "CCGC" is tried before "CC", "HMAX" before "MA", etc.
_all_tokens.sort(key=len, reverse=True)

_PROVIDER_RE = re.compile(
    r"(?<![A-Za-z0-9])(" + "|".join(re.escape(t) for t in _all_tokens) + r")(?![A-Za-z0-9])"
)


def parse_provider(filename: str) -> str | None:
    match = _PROVIDER_RE.search(filename)
    if not match:
        return None
    return _alias_to_canonical[match.group(1)]
